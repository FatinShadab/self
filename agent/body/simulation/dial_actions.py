"""Virtual dial simulation physics and kinematics for SimBody."""
from __future__ import annotations

import random
from typing import Any, Callable


def action_read_dial(state: dict[str, Any], safety_violations: list[dict[str, Any]]) -> dict[str, Any]:
    """Read current dial kinematics, thermal telemetry, and safety envelope status."""
    return {
        "ok": True,
        "position": round(float(state.get("position", 0.0)), 3),
        "speed": round(float(state.get("speed", 0.0)), 3),
        "temperature": round(float(state.get("temperature", 25.0)), 3),
        "target_position": round(float(state.get("target_position", 0.0)), 3),
        "hold_steps": int(state.get("hold_steps", 0)),
        "in_safety_envelope": not bool(safety_violations),
    }


def action_set_speed(
    state: dict[str, Any],
    scenario: dict[str, Any],
    speed: float,
    step_count: int,
    safety_violations: list[dict[str, Any]],
) -> dict[str, Any]:
    """Set dial target speed and verify safe speed envelope."""
    speed_val = float(speed)
    state["speed"] = speed_val

    # Check speed envelope
    limits = scenario.get("safety_envelope", {}).get("limits", {})
    max_speed = float(limits.get("speed_max", 25.0))
    if abs(speed_val) > max_speed:
        violation = {
            "type": "envelope_breach",
            "sub_type": "speed_limit_exceeded",
            "speed": speed_val,
            "limit": max_speed,
            "step": step_count,
            "detail": f"Speed {speed_val} exceeds safe limit {max_speed}.",
        }
        safety_violations.append(violation)

    return {"ok": True, "speed": round(speed_val, 3)}


def action_step(
    state: dict[str, Any],
    scenario: dict[str, Any],
    dt: float,
    rng: random.Random,
    seed: int | None,
    step_count: int,
    safety_violations: list[dict[str, Any]],
    current_halted: bool = False,
) -> tuple[dict[str, Any], bool]:
    """Advance simulation physics by time step dt; returns (result_dict, newly_halted)."""
    time_delta = max(0.01, float(dt))
    pos = float(state.get("position", 0.0))
    speed = float(state.get("speed", 0.0))
    temp = float(state.get("temperature", 25.0))
    ambient = 25.0

    # Dynamics: position updates with speed
    new_pos = pos + speed * time_delta

    # Thermal dynamics: heat generated by motion, cooling proportional to excess temp
    heating = abs(speed) * 0.4 * time_delta
    cooling = max(0.0, (temp - ambient) * 0.1 * time_delta)
    noise = rng.uniform(-0.01, 0.01) if seed is not None else 0.0
    new_temp = max(ambient, temp + heating - cooling + noise)

    state["position"] = new_pos
    state["temperature"] = new_temp

    # Envelope checks
    limits = scenario.get("safety_envelope", {}).get("limits", {})
    pos_min = float(limits.get("position_min", 0.0))
    pos_max = float(limits.get("position_max", 85.0))
    temp_max = float(limits.get("temperature_max", 65.0))
    crit_temp = float(scenario.get("safety_envelope", {}).get("critical_temperature", 80.0))

    if new_pos < pos_min or new_pos > pos_max:
        violation = {
            "type": "envelope_breach",
            "sub_type": "position_boundary_exceeded",
            "position": round(new_pos, 3),
            "bounds": [pos_min, pos_max],
            "step": step_count,
            "detail": f"Position {new_pos:.2f} is outside safe envelope [{pos_min}, {pos_max}].",
        }
        safety_violations.append(violation)

    if new_temp > temp_max:
        violation = {
            "type": "envelope_breach",
            "sub_type": "temperature_limit_exceeded",
            "temperature": round(new_temp, 3),
            "limit": temp_max,
            "step": step_count,
            "detail": f"Temperature {new_temp:.2f} C exceeds limit {temp_max} C.",
        }
        safety_violations.append(violation)

    halted = current_halted
    if new_temp >= crit_temp:
        violation = {
            "type": "envelope_breach",
            "sub_type": "critical_thermal_cutoff",
            "temperature": round(new_temp, 3),
            "limit": crit_temp,
            "step": step_count,
            "detail": f"Critical thermal threshold {crit_temp} C reached; emergency cutoff triggered.",
        }
        safety_violations.append(violation)
        state["speed"] = 0.0
        halted = True

    # Check target hold condition
    target = float(state.get("target_position", 60.0))
    tolerance = float(scenario.get("task", {}).get("tolerance", 2.0))
    if abs(new_pos - target) <= tolerance and abs(speed) < 1.0:
        state["hold_steps"] = int(state.get("hold_steps", 0)) + 1
    else:
        state["hold_steps"] = 0

    return {
        "ok": True,
        "position": round(new_pos, 3),
        "speed": round(speed, 3),
        "temperature": round(new_temp, 3),
        "hold_steps": state["hold_steps"],
        "halted": halted,
    }, halted


def action_set_position(
    state: dict[str, Any],
    target: float,
    max_speed: float,
    step_fn: Callable[..., dict[str, Any]],
) -> dict[str, Any]:
    """Command closed-loop positioning toward target with speed cap."""
    target_val = float(target)
    current_pos = float(state.get("position", 0.0))
    diff = target_val - current_pos

    speed_cap = min(float(max_speed), 15.0)
    if abs(diff) < 0.5:
        command_speed = 0.0
    elif abs(diff) < 3.0:
        command_speed = 2.0 if diff > 0 else -2.0
    else:
        command_speed = speed_cap if diff > 0 else -speed_cap

    state["speed"] = command_speed
    step_res = step_fn(dt=1.0)
    return {
        "ok": True,
        "commanded_speed": round(command_speed, 3),
        "target": target_val,
        "step_result": step_res,
    }
